let activePhoto = 0;
let startX = 0;
const lightbox = $("#lightbox");
const lightboxImage = $("#lightboxImage");

function openLightbox(index) {
  activePhoto = index;
  updateLightbox();
  lightbox.classList.add("open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.classList.add("locked");
  $("#lightboxClose").focus();
}

function closeLightbox() {
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.classList.remove("locked");
}

function moveLightbox(step) {
  activePhoto = (activePhoto + step + CONFIG.photos.length) % CONFIG.photos.length;
  updateLightbox();
}

function updateLightbox() {
  const photo = CONFIG.photos[activePhoto];
  lightboxImage.src = encodePath(photo.file);
  lightboxImage.alt = photo.alt;
  $("#lightboxCaption").textContent = photo.alt;
  $("#photoCounter").textContent = `${activePhoto + 1} / ${CONFIG.photos.length}`;
}

$("#lightboxClose").addEventListener("click", closeLightbox);
$("#lightboxPrev").addEventListener("click", () => moveLightbox(-1));
$("#lightboxNext").addEventListener("click", () => moveLightbox(1));
lightbox.addEventListener("click", (event) => {
  if (event.target === lightbox) closeLightbox();
});
lightbox.addEventListener("touchstart", (event) => {
  startX = event.changedTouches[0].clientX;
}, { passive: true });
lightbox.addEventListener("touchend", (event) => {
  const delta = event.changedTouches[0].clientX - startX;
  if (Math.abs(delta) > 45) moveLightbox(delta > 0 ? -1 : 1);
}, { passive: true });
document.addEventListener("keydown", (event) => {
  if (!lightbox.classList.contains("open")) return;
  if (event.key === "Escape") closeLightbox();
  if (event.key === "ArrowLeft") moveLightbox(-1);
  if (event.key === "ArrowRight") moveLightbox(1);
});

