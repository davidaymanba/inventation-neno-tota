function calendarRange(kind) {
  const startTime = kind === "ceremony" ? CONFIG.ceremonyTime : CONFIG.receptionTime;
  const fallbackTime = /^\d{2}:\d{2}$/.test(startTime) ? startTime : "18:00";
  const start = new Date(`${CONFIG.weddingDate}T${fallbackTime}:00+02:00`);
  const end = new Date(start.getTime() + 2 * 60 * 60 * 1000);
  return { start, end };
}

function toCalendarDate(date) {
  return date.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
}

function downloadIcs(event) {
  const { start, end } = calendarRange(event.kind);
  const ics = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Marcleno and Reta Wedding//EN",
    "BEGIN:VEVENT",
    `UID:${event.kind}-${CONFIG.weddingDate}@marcleno-reta`,
    `DTSTAMP:${toCalendarDate(new Date())}`,
    `DTSTART:${toCalendarDate(start)}`,
    `DTEND:${toCalendarDate(end)}`,
    `SUMMARY:${event.title} - ${tr().groomName} & ${tr().brideName}`,
    `LOCATION:${event.location}`,
    `DESCRIPTION:${event.description}`,
    "END:VEVENT",
    "END:VCALENDAR"
  ].join("\r\n");
  const blob = new Blob([ics], { type: "text/calendar" });
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = `${event.kind}-marcleno-reta.ics`;
  link.click();
  URL.revokeObjectURL(link.href);
}

function googleCalendarUrl(event) {
  const { start, end } = calendarRange(event.kind);
  const params = new URLSearchParams({
    action: "TEMPLATE",
    text: `${event.title} - ${CONFIG.displayNames}`,
    dates: `${toCalendarDate(start)}/${toCalendarDate(end)}`,
    details: event.description,
    location: event.location
  });
  return `https://calendar.google.com/calendar/render?${params.toString()}`;
}

