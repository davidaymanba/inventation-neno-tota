function initMusic() {
  const player = $("#musicPlayer");
  const toggle = $("#musicToggle");
  const selectedTrack = pickMusicTrack();
  if (!selectedTrack) {
    toggle.hidden = true;
    return;
  }
  player.src = selectedTrack;
  player.volume = 0.72;
  player.currentTime = 0;

  const startMusic = async () => {
    try {
      if (player.currentTime > 0 && player.paused) player.currentTime = 0;
      await player.play();
      toggle.setAttribute("aria-pressed", "true");
    } catch (error) {
      toggle.setAttribute("aria-pressed", "false");
    }
  };

  startMusic();
  document.addEventListener("pointerdown", startMusic, { once: true });
  document.addEventListener("keydown", startMusic, { once: true });

  toggle.addEventListener("click", async () => {
    if (player.paused) {
      await startMusic();
    } else {
      player.pause();
      toggle.setAttribute("aria-pressed", "false");
    }
  });
}

function initCursor() {
  const cursor = $("#customCursor");
  if (!cursor || !window.matchMedia("(hover: hover) and (pointer: fine)").matches) return;

  let x = window.innerWidth / 2;
  let y = window.innerHeight / 2;
  let ringX = x;
  let ringY = y;
  const dot = cursor.querySelector(".cursor-dot");
  const ring = cursor.querySelector(".cursor-ring");

  window.addEventListener("mousemove", (event) => {
    x = event.clientX;
    y = event.clientY;
    cursor.classList.add("visible");
    dot.style.transform = `translate(${x}px, ${y}px) translate(-50%, -50%)`;
  });

  document.addEventListener("mouseover", (event) => {
    if (event.target.closest("a, button, .gallery-item, .lightbox-nav, .lightbox-close")) {
      cursor.classList.add("active");
    }
  });

  document.addEventListener("mouseout", (event) => {
    if (event.target.closest("a, button, .gallery-item, .lightbox-nav, .lightbox-close")) {
      cursor.classList.remove("active");
    }
  });

  window.addEventListener("mouseleave", () => cursor.classList.remove("visible"));

  function animate() {
    ringX += (x - ringX) * 0.18;
    ringY += (y - ringY) * 0.18;
    ring.style.transform = `translate(${ringX}px, ${ringY}px) translate(-50%, -50%)`;
    requestAnimationFrame(animate);
  }

  animate();
}

